with st.sidebar:
    st.caption("Mail memory · POC")
    st.text_input("Mail service", value=MAIL, disabled=True)
    st.text_input("LLM endpoint", value=LLM_BASE or "not configured (lexical only)", disabled=True)
    if st.button("Reset chat"):
        st.session_state.chat = []
        st.rerun()
    st.caption(f"{mail_get('/api/threads', limit=1).get('total', 0)} threads indexed")

st.session_state.setdefault("chat", [])
st.session_state.setdefault("open_tabs", [])
st.session_state.setdefault("active_tab", None)
st.session_state.setdefault("draft_subject", {})

# Deep link: /?mail=<message_id> opens that thread in a tab
linked = st.query_params.get("mail")
if linked and linked not in st.session_state.get("_seen_link", []):
    rec = mail_get(f"/api/mail/{linked}")
    if rec:
        open_tab(rec["thread_id"])
        st.session_state.setdefault("_seen_link", []).append(linked)

left, right = st.columns([1, 1], gap="large")

# ---------------------------------------------------------------- left: chat
with left:
    st.subheader("Ask the mailbox")
    for turn in st.session_state.chat:
        with st.chat_message(turn["role"]):
            st.markdown(turn["content"], unsafe_allow_html=False)

    question = st.chat_input("Ask about a past issue, customer, invoice, contract…")
    if question:
        st.session_state.chat.append({"role": "user", "content": question})
        with st.chat_message("user"):
            st.markdown(question)

        hits = search(question)
        prompt = (
            f"Question: {question}\n\n"
            f"Sources ({len(hits)}):\n{context_block(hits)}\n\n"
            "Answer with citations. If unrelated, say so."
        )
        with st.chat_message("assistant"):
            if llm() is None:
                answer = fallback_answer(question, hits)
                st.markdown(answer)
            else:
                try:
                    answer = st.write_stream(
                        stream_chat(
                            [{"role": "system", "content": SYSTEM}, {"role": "user", "content": prompt}]
                        )
                    )
                except LLMUnavailable as exc:
                    answer = fallback_answer(question, hits)
                    st.caption(f"LLM unavailable ({exc}) — lexical answer below.")
                    st.markdown(answer)
            render_sources(hits)

        if hits:
            open_tab(hits[0]["thread_id"])
        st.session_state.chat.append({"role": "assistant", "content": answer})

# ---------------------------------------------------------------- right: mailbox tabs
def render_thread(tid: str) -> None:
    detail = thread_detail(tid)
    msgs = detail.get("messages", [])
    meta = detail.get("thread", {})
    top = st.columns([0.7, 0.3])
    top[0].caption(
        f"{len(msgs)} messages · {meta.get('lang', '?')} · source {meta.get('source', '?')}"
    )
    if top[1].button("close tab", key=f"close-{tid}"):
        st.session_state.open_tabs = [t for t in st.session_state.open_tabs if t != tid]
        st.rerun()

    for m in msgs:
        synthetic = " · *synthetic date*" if m.get("synthetic_date") else ""
        with st.expander(
            f"{m['date'][:10]} · {m['from']['email']} · {m['subject'][:60]}",
            expanded=m["id"] == st.query_params.get("mail"),
        ):
            st.markdown(
                anchor(f"{PUBLIC}{m['permalink']}", "open in new tab")
                + "  ·  "
                + f'<a href="{PUBLIC}/api/mail/{m["id"]}" target="_blank" rel="noopener">JSON</a>'
                + synthetic,
                unsafe_allow_html=True,
            )
            st.text(m["body"][:6000])

    last = msgs[-1] if msgs else None
    st.divider()
    st.markdown("**Draft reply**")
    instruction = st.text_input(
        "What should the reply say?",
        placeholder="e.g. confirm the refund and ask for the invoice number",
        key=f"instr-{tid}",
    )
    cols = st.columns([0.5, 0.5])
    if cols[0].button("Draft with agent", key=f"draft-{tid}", disabled=last is None):
        thread_text = "\n\n".join(
            f'<mail date="{m["date"][:10]}" from="{m["from"]["email"]}" '
            f'subject="{m["subject"]}">\n{m["body"][:MAX_CHARS]}\n</mail>'
            for m in msgs[-4:]
        )
        user = (
            f"Thread to reply to (oldest to newest):\n{thread_text}\n\n"
            f"Instruction: {instruction or 'Write an appropriate reply.'}\n"
            f"Reply as the mailbox owner to {last['from']['email']}."
        )
        if llm() is None:
            st.session_state[f"body-{tid}"] = (
                f"(no LLM configured — draft skeleton)\n\n"
                f"Hello,\n\nregarding: {last['subject']}\n\n{instruction}\n\nBest regards"
            )
            st.rerun()
        else:
            placeholder = st.empty()
            text = ""
            for piece in stream_chat(
                [{"role": "system", "content": DRAFT_SYSTEM}, {"role": "user", "content": user}]
            ):
                text += piece
                placeholder.markdown(text)
            st.session_state[f"body-{tid}"] = text
            st.rerun()

    st.text_input("Subject", key=f"subject-{tid}", value=last["subject"] if last else "")
    st.text_area("Body", key=f"body-{tid}", height=240)

    if cols[1].button("Save draft", key=f"save-{tid}") and last is not None:
        res = mail_post(
            "/api/draft",
            {
                "thread_id": tid,
                "subject": st.session_state.get(f"subject-{tid}", last["subject"]),
                "body": st.session_state.get(f"body-{tid}", ""),
                "in_reply_to": last["id"],
            },
        )
        if res.get("ok"):
            st.success("draft saved to the dummy mailbox")


with right:
    st.subheader("Mailbox")
    f1, f2, f3 = st.columns([0.45, 0.22, 0.33])
    q = f1.text_input(
        "Search", key="mbox_q", placeholder="subject, sender, body…", label_visibility="collapsed"
    )
    lang = f2.selectbox(
        "Language", ["All", "EN", "DE"], key="mbox_lang", label_visibility="collapsed"
    )
    mode = f3.selectbox(
        "Sort",
        ["Newest", "Oldest", "Mixed"],
        index=2,
        key="mbox_mode",
        label_visibility="collapsed",
    )

    per_page = 12
    page = int(st.session_state.get("mbox_page", 0))
    params = {
        "q": q,
        "limit": per_page,
        "offset": page * per_page,
        "order": "asc" if mode == "Oldest" else "desc",
        "mode": "mixed" if mode.startswith("Mixed") else "date",
    }
    if lang != "All":
        params["lang"] = lang.lower()
    data = mail_get("/api/threads", **params)
    total = data.get("total", 0)
    rows = data.get("items", [])
    pages = max(1, (total + per_page - 1) // per_page)
    page = min(page, pages - 1)
    st.session_state.mbox_page = page

    for t in rows:
        cols = st.columns([0.26, 0.60, 0.14])
        mark = "*" if t["synthetic_date"] else ""
        cols[0].markdown(
            f'<span style="white-space:nowrap">{t["last_date"][:10]}{mark}</span>',
            unsafe_allow_html=True,
        )
        if cols[1].button(
            f'{t["lang"]} · {t["subject"][:72]}',
            key=f'mbox-{t["thread_id"]}',
            use_container_width=True,
        ):
            open_tab(t["thread_id"])
            st.rerun()
        cols[2].markdown(f'{t["messages"]}')

    nav = st.columns([0.2, 0.2, 0.6])
    if nav[0].button("← Prev", disabled=page == 0):
        st.session_state.mbox_page = page - 1
        st.rerun()
    if nav[1].button("Next →", disabled=page + 1 >= pages):
        st.session_state.mbox_page = page + 1
        st.rerun()
    nav[2].caption(
        f"{total} threads · page {page + 1}/{pages} · right column = messages · * = generated date"
    )

    if st.session_state.open_tabs:
        st.divider()
        tabs = st.tabs(
            [
                thread_detail(t).get("thread", {}).get("subject", t)[:28]
                for t in st.session_state.open_tabs
            ]
        )
        for tab, tid in zip(tabs, st.session_state.open_tabs):
            with tab:
                render_thread(tid)
